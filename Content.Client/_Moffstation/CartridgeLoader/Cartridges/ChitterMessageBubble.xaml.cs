using Content.Shared._Moffstation.CartridgeLoader.Cartridges;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Maths;

namespace Content.Client._Moffstation.CartridgeLoader.Cartridges;

[GenerateTypedNameReferences]
public sealed partial class ChitterMessageBubble : BoxContainer
{
    private static readonly Color OwnBubbleColor = new(0f, 0.68f, 0.94f);
    private static readonly Color OtherBubbleColor = new(0.13f, 0.69f, 0.29f);

    public string SenderName
    {
        set => SenderLabel.Text = value;
    }

    public string Message
    {
        set => MessageLabel.Text = value;
    }

    public TimeSpan Timestamp
    {
        set => TimestampLabel.Text = TimeSpan.FromSeconds(Math.Truncate(value.TotalSeconds)).ToString();
    }

    public bool IsOwn
    {
        set
        {
            BubbleBackground.ModulateSelfOverride = value ? OwnBubbleColor : OtherBubbleColor;
            SenderLabel.Visible = !value;
        }
    }

    public bool DeliveryFailed
    {
        set => FailedLabel.Visible = value;
    }

    public ChitterMessageBubble()
    {
        RobustXamlLoader.Load(this);
    }
}
